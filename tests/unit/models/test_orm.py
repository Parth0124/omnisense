"""Unit tests for `models/orm/` -- the mappings, their constraints and their shape.

Three kinds of assertion live here, and they fail for three different reasons.

**Behavioural.** Rows round-trip, enum columns come back as members, checks
reject what they were written to reject, cascades fire. These run against SQLite
(`tests/conftest.py`), which is enough because every constraint under test is
plain SQL that both engines enforce identically. Anything PostgreSQL-specific --
`JSONB` operators, partial-index planning, `TIMESTAMPTZ` fidelity -- belongs in
`tests/integration/db/`.

**Structural.** Every constraint and index carries a name generated by the
convention in `models/orm/base.py`. This is not style. An unnamed constraint gets
a server-generated name that differs between "created by `CREATE TABLE`" and
"created by `ALTER TABLE`", so the Alembic migration that created it cannot drop
it -- discovered on the downgrade path, months later, in production.

**Prohibitive.** `docs/data-stores.md` §3.1 forbids PostgreSQL from holding
payload bodies, embedding vectors and plaintext credentials. Those are the three
mistakes that quietly break the two-tier rule the whole storage design rests on,
and none of them announces itself: the schema still works, the rebuild guarantee
just stops being true. Asserting on column names and types is the cheapest place
to catch a column that should never have been added.
"""

