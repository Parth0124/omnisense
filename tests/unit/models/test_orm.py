    def test_stored_as_plain_varchar_without_a_constraint(self) -> None:
        """No `CREATE TYPE`, and no `CHECK` enumerating the members either.

        Either one would mean a new `Platform` cannot be written until a
        migration has run everywhere -- the coordinated deploy the tolerant enum
        exists to avoid. A `CHECK ... IN (...)` is the version of that mistake
        which looks portable and therefore harmless.
        """
        for table_name, column_name in enum_columns():
            column = table_named(table_name).columns[column_name]
            assert isinstance(column.type.impl_instance, String)

        for table in tables():
            for constraint in table.constraints:
                if isinstance(constraint, CheckConstraint):
                    assert " IN (" not in str(constraint.sqltext).upper()

    @pytest.mark.parametrize(("table_name", "column_name"), enum_columns())
    async def test_reads_back_as_an_enum_member(
        self, db_session: AsyncSession, table_name: str, column_name: str
    ) -> None:
        """Not a bare `str`.

        `TolerantStrEnum` members compare equal to their value, so `== "reddit"`
        would pass either way; identity against the member is what actually
        distinguishes a decoded column from an undecoded one, and callers do
        `is Platform.REDDIT` and `.is_retrievable` on these.
        """
        row = await SEEDERS[table_name](db_session)
        reloaded = await reload_row(db_session, row)
        value = getattr(reloaded, column_name)

        assert isinstance(value, enum_class_of(table_name, column_name))

    @pytest.mark.parametrize(("table_name", "column_name"), enum_columns())
    async def test_value_from_a_newer_writer_degrades_or_raises(
        self, db_session: AsyncSession, table_name: str, column_name: str
    ) -> None:
        """The behaviour the column type exists for, asserted per column.

        A tolerant vocabulary degrades an unrecognized member to `UNKNOWN`
        exactly as it does over Kafka, so a reader on older code survives a
        rolling deploy. A closed one -- `SignalStatus`, owned entirely by the
        pipeline -- must instead raise, because an unrecognized value there is a
        bug rather than version skew. Which of the two applies is read off the
        enum, so the test follows the vocabulary rather than a hardcoded list.
        """
        enum_cls = enum_class_of(table_name, column_name)
        row = await SEEDERS[table_name](db_session)
        await db_session.execute(
            text(f"UPDATE {table_name} SET {column_name} = :v").bindparams(
                v="member_from_a_newer_build"
            )
        )
        await db_session.commit()

        if "UNKNOWN" in enum_cls.__members__:
            reloaded = await reload_row(db_session, row)
            assert getattr(reloaded, column_name) is enum_cls.UNKNOWN
        else:
            with pytest.raises(ValueError, match="is not a valid"):
                await reload_row(db_session, row)

    def test_signal_status_is_the_closed_one(self) -> None:
        """Guards the branch above: if `SignalStatus` ever gains `UNKNOWN`, the
        parametrized test silently stops asserting that anything fails loudly."""
        assert "UNKNOWN" not in SignalStatus.__members__

    async def test_case_insensitive_value_still_resolves(self, db_session: AsyncSession) -> None:
        """Providers are inconsistent about casing; `REDDIT` is not unknown."""
        await seed_signal(db_session)
        await db_session.execute(text("UPDATE signals SET platform = 'REDDIT'"))
        await db_session.commit()

        assert (await reload(db_session, SignalRow, "sig_1")).platform is Platform.REDDIT

    async def test_writes_the_value_not_the_repr(self, db_session: AsyncSession) -> None:
        """`Platform.REDDIT` must land as `reddit`, so that a hand-written SQL
        report or an Alembic data migration reads the same values the pipeline
        does."""
        await seed_signal(db_session)
        stored = await db_session.scalar(text("SELECT platform FROM signals WHERE id = 'sig_1'"))

        assert stored == "reddit"


