def tables() -> list[Table]:
    """Every mapped table, ordered by name.

    Looked up through `.name` rather than through the `metadata.tables` keys:
    `bind_for_testing()` clears `Table.schema` but leaves the dictionary keyed by
    the original `omnisense.`-qualified string, so the keys and `Table.key`
    disagree for the whole unit run.
    """
    return sorted(metadata.tables.values(), key=lambda t: t.name)


def table_named(name: str) -> Table:
    return next(t for t in tables() if t.name == name)


async def reload[T: Base](session: AsyncSession, model: type[T], pk: str) -> T:
    """Re-read a row from the database, bypassing the identity map.

    `expunge_all()` first. With `expire_on_commit=False` a plain `SELECT` returns
    the instance the session already holds, still carrying whatever Python put
    there -- so an assertion on it can pass even if nothing was ever written.
    Dropping the instance forces the assertions onto what the database actually
    stored, which is the only thing a round-trip test is about.
    """
    session.expunge_all()
    return (await session.execute(select(model).where(model.id == pk))).scalar_one()


async def reload_row[T: Base](session: AsyncSession, row: T) -> T:
    """`reload`, for a row whose key is not a single column called `id`."""
    model = type(row)
    clause = _pk_filter(model, row)
    session.expunge_all()
    return (await session.execute(select(model).where(clause))).scalar_one()


def _pk_filter(model: type[Base], row: Base) -> Any:
    """A WHERE clause selecting exactly `row`, whatever its key looks like.

    Most tables here key on a column called `id`, and this used to assume both --
    the name and that there was only one. `identity_links` keys on `person_id`,
    and `feature_links` on the *pair* `(feature_id, artifact_id)`, both
    deliberately: an account belongs to one human, while an artifact genuinely
    belongs to several features. Reading the key off the mapper means a table with
    a natural or composite key needs no special case here.
    """
    return and_(
        *(
            getattr(model, column.name) == getattr(row, column.name)
            for column in inspect(model).primary_key
        )
    )


async def count(session: AsyncSession, model: type[Any]) -> int:
    return (await session.scalar(select(func.count()).select_from(model))) or 0


