class TestNamingConvention:
    """Every constraint and index must be named by the convention in
    `models/orm/base.py`.

    Without it, Alembic autogenerates names from PostgreSQL's defaults -- which
    differ between "created by `CREATE TABLE`" and "created by `ALTER TABLE`" --
    and the migration that created a constraint cannot drop it. The failure
    appears on the downgrade path, long after the review that would have caught
    it.
    """

    @staticmethod
    def _named_objects() -> list[tuple[str, Constraint | Index]]:
        out: list[tuple[str, Constraint | Index]] = []
        for table in tables():
            out += [(table.name, c) for c in table.constraints]
            out += [(table.name, i) for i in table.indexes]
        return out

    def test_nothing_is_anonymous(self) -> None:
        for table_name, obj in self._named_objects():
            assert isinstance(obj.name, str) and obj.name, (
                f"{type(obj).__name__} on {table_name} has no name"
            )

    def test_primary_keys(self) -> None:
        for table in tables():
            for constraint in table.constraints:
                if isinstance(constraint, PrimaryKeyConstraint):
                    assert constraint.name == f"pk_{table.name}"

    def test_unique_constraints(self) -> None:
        for table in tables():
            for constraint in table.constraints:
                if isinstance(constraint, UniqueConstraint):
                    names = "_".join(c.name for c in constraint.columns)
                    assert constraint.name == f"uq_{table.name}_{names}"

    def test_foreign_keys(self) -> None:
        for table in tables():
            for constraint in table.constraints:
                if isinstance(constraint, ForeignKeyConstraint):
                    names = "_".join(c.name for c in constraint.columns)
                    referred = constraint.referred_table.name
                    assert constraint.name == f"fk_{table.name}_{names}_{referred}"

    def test_check_constraints_are_explicitly_named(self) -> None:
        """`ck_%(table_name)s_%(constraint_name)s` needs the `name=` argument.

        A `CheckConstraint` without one does not fall back to a default: the
        convention raises `InvalidRequestError` the moment the constraint is
        attached to its table, which is at import. So this assertion cannot fail
        in the ordinary way -- omitting a name breaks collection of the whole
        suite instead. It stays because it is the readable statement of the rule,
        and because it does catch the case the raise cannot: a name that is
        present but does not describe the table it is on.
        """
        for table in tables():
            for constraint in table.constraints:
                if isinstance(constraint, CheckConstraint):
                    assert constraint.name is not None
                    prefix = f"ck_{table.name}_"
                    assert constraint.name.startswith(prefix)
                    assert len(constraint.name) > len(prefix)

    def test_indexes(self) -> None:
        for table in tables():
            for index in table.indexes:
                assert index.name is not None
                expected_prefix = "uq_" if index.unique else "ix_"
                assert index.name.startswith(expected_prefix)
                assert table.name in index.name

    def test_names_are_unique_across_the_schema(self) -> None:
        """PostgreSQL puts indexes -- including those backing PRIMARY KEY and
        UNIQUE -- in one per-schema namespace, so two tables cannot reuse a name
        even though the constraint would be per-table."""
        names = [obj.name for _, obj in self._named_objects()]
        duplicates = {name for name in names if names.count(name) > 1}
        assert not duplicates


