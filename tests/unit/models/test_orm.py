def enum_columns() -> list[tuple[str, str]]:
    """Every `TolerantEnumType` column, derived from the metadata.

    Generated rather than listed so a new enum column is covered the moment it is
    mapped. That matters here more than elsewhere: the whole point of
    `TolerantEnumType` is behaviour on read, which nothing else exercises.
    """
    return sorted(
        (table.name, column.name)
        for table in tables()
        for column in table.columns
        if isinstance(column.type, TolerantEnumType)
    )


def enum_class_of(table_name: str, column_name: str) -> type[Any]:
    column_type = table_named(table_name).columns[column_name].type
    assert isinstance(column_type, TolerantEnumType)
    return column_type.enum_cls


