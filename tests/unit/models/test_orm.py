class TestTimestampMixin:
    async def test_created_at_comes_from_the_database(self, db_session: AsyncSession) -> None:
        """Not from Python.

        With workers on several hosts, Python-side timestamps skew and
        `ORDER BY created_at` stops being a stable ordering. The assertion that
        the attribute is `None` before the flush is what proves the value was
        produced by the server default rather than by the mapping.
        """
        row = make_investigation()
        assert row.created_at is None

        db_session.add(row)
        await db_session.commit()
        await db_session.refresh(row)

        assert isinstance(row.created_at, datetime)
        assert isinstance(row.updated_at, datetime)

    async def test_updated_at_moves_on_update(self, db_session: AsyncSession) -> None:
        """`onupdate` is SQL, so it fires for writers that never load the object.

        Seeded with a stale value rather than compared against `created_at`:
        SQLite's `CURRENT_TIMESTAMP` has one-second resolution, so a fresh row
        updated immediately would show two identical timestamps and the
        assertion would prove nothing.
        """
        stale = datetime(2000, 1, 1, 0, 0, 0)
        await _add(db_session, make_investigation(created_at=stale, updated_at=stale))

        row = await reload(db_session, InvestigationRow, "inv_1")
        row.query = "reworded question"
        await db_session.commit()
        await db_session.refresh(row)

        assert row.updated_at > stale
        assert row.created_at == stale, "created_at must not be rewritten by an update"

    async def test_a_raw_insert_still_gets_both(self, db_session: AsyncSession) -> None:
        """The case that matters for backfills and `psql`.

        A Python-side `default=` would leave these NULL for any writer that does
        not go through the ORM, and the columns are `NOT NULL`.
        """
        await db_session.execute(
            text(
                "INSERT INTO investigations"
                " (id, query, status, step_count, token_input, token_output, cost_usd)"
                " VALUES ('inv_raw', 'from a migration', 'queued', 0, 0, 0, 0)"
            )
        )
        await db_session.commit()

        row = await reload(db_session, InvestigationRow, "inv_raw")
        assert row.created_at is not None
        assert row.updated_at is not None


