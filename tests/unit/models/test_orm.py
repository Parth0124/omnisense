async def _add_only(session: AsyncSession, row: Any) -> None:
    """Stage a row without committing -- the test commits and expects the raise."""
    session.add(row)


async def _seed_then(
    session: AsyncSession,
    seeder: Callable[[AsyncSession], Awaitable[Any]],
    row: Any,
) -> None:
    """Insert the parents a foreign key needs, then stage the offending row."""
    await seeder(session)
    session.add(row)


class TestCheckConstraints:
    @pytest.mark.parametrize(
        ("constraint_name", "prepare"),
        CHECK_VIOLATIONS,
        ids=[f"{i}-{name}" for i, (name, _) in enumerate(CHECK_VIOLATIONS)],
    )
    async def test_rejects_the_value_it_names(
        self,
        db_session: AsyncSession,
        constraint_name: str,
        prepare: Callable[[AsyncSession], Awaitable[None]],
    ) -> None:
        """Each CHECK is fed exactly the value it was written to refuse.

        The constraint *name* is asserted, not just "something failed": several
        of these tables carry five or six checks, and a row that violates two at
        once would otherwise let a broken constraint hide behind a working one.
        """
        await prepare(db_session)

        with pytest.raises(IntegrityError) as excinfo:
            await db_session.commit()

        assert constraint_name in str(excinfo.value.orig)

    def test_every_check_constraint_is_exercised(self) -> None:
        """A CHECK nobody tests is a CHECK nobody knows is inverted.

        Reversing a comparison in one of these expressions is invisible -- the
        migration applies, the table accepts every row it accepted before, and
        the constraint simply stops rejecting anything.
        """
        declared = {
            constraint.name
            for table in tables()
            for constraint in table.constraints
            if isinstance(constraint, CheckConstraint)
        }
        assert declared == {name for name, _ in CHECK_VIOLATIONS}


