VECTOR_TOKENS = frozenset({"vector", "vectors", "embedding", "embeddings"})
RAW_BODY_TOKENS = frozenset({"raw", "payload", "body", "html", "blob", "bytes", "binary"})
SECRET_PATTERN = re.compile(
    r"credential|secret|password|passphrase|api_key|private_key|plaintext|bearer"
)

VECTOR_EXEMPT: dict[tuple[str, str], str] = {
    ("signals", "embeddings"): (
        "EmbeddingRef records -- model, dimensions, collection, point id. The "
        "floats live in Qdrant; these refs are what makes a model migration "
        "tractable."
    ),
    ("signals", "indexed_vector_at"): (
        "A timestamp recording that Qdrant was written, not what was written."
    ),
}

RAW_BODY_EXEMPT: dict[tuple[str, str], str] = {
    ("artifacts", "body"): (
        "A commit message, a pull request description, a Slack message. Bounded "
        "prose the platform's API returns as a field -- not a scraped document. "
        "It is also the text every 'why did we decide X' answer quotes, so it "
        "has to be queryable here rather than behind an object-store fetch."
    ),
    ("signals", "raw_object_key"): "The R2 key. A pointer, not the bytes.",
    ("signals", "raw_sha256"): "Digest of the R2 object, for integrity checks.",
    ("signals", "author_payload"): (
        "The residual Author fields -- bounded metadata from the item envelope, not the item body."
    ),
    ("report_sections", "body"): (
        "Narrative this system generated, queried by attribute and rewritten by "
        "the Critic. R2 holds immutable content-addressed objects, which this is "
        "not."
    ),
}

SECRET_EXEMPT: dict[tuple[str, str], str] = {
    ("connector_accounts", "encrypted_credentials"): "Fernet ciphertext, never plaintext.",
    ("connector_accounts", "credential_key_version"): (
        "Which key generation opens the ciphertext -- required for rotation."
    ),
    ("connector_accounts", "credential_updated_at"): (
        "Drives the 90-day rotation reminder; the only credential fact the API may expose."
    ),
}


def columns() -> list[tuple[str, str, Any]]:
    return [(t.name, c.name, c) for t in tables() for c in t.columns]


class TestForbiddenColumns:
    """`docs/data-stores.md` §3.1: no payload bodies, no vectors, no plaintext
    secrets.

    The exemption tables above are the point of these tests, not a loophole in
    them. Each one names a column and says why it is not the thing it looks like.
    A new column matching any of these patterns fails until somebody writes that
    sentence -- which is exactly the review the two-tier rule needs, and exactly
    the review that does not happen when the only record is a paragraph in a
    design document.
    """

    def test_no_column_holds_an_embedding_vector(self) -> None:
        """Vectors belong in Qdrant. A float array here would make PostgreSQL
        the only place they live and break the rebuild guarantee in both
        directions -- the vectors could not be regenerated from it, and it could
        not be dumped without them."""
        for table_name, column_name, _ in columns():
            tokens = set(column_name.lower().split("_"))
            if tokens & VECTOR_TOKENS:
                assert (table_name, column_name) in VECTOR_EXEMPT, (
                    f"{table_name}.{column_name} looks like a vector column"
                )

    def test_no_column_can_structurally_hold_a_float_array(self) -> None:
        """The teeth behind the name check: `ARRAY(Float)` or a `vector` type
        would pass any naming rule while storing the embeddings outright."""
        for table_name, column_name, column in columns():
            assert not isinstance(column.type, ARRAY), f"{table_name}.{column_name} is an ARRAY"
            type_name = type(column.type).__name__.upper()
            assert "VECTOR" not in type_name, f"{table_name}.{column_name} is {type_name}"

    def test_no_column_holds_a_raw_payload_body(self) -> None:
        """A `TEXT` column of scraped HTML turns the write-ahead log into a
        bandwidth problem, and replicates the bytes to every standby."""
        for table_name, column_name, _ in columns():
            tokens = set(column_name.lower().split("_"))
            if tokens & RAW_BODY_TOKENS:
                assert (table_name, column_name) in RAW_BODY_EXEMPT, (
                    f"{table_name}.{column_name} looks like a raw payload column"
                )

    def test_binary_columns_are_limited_to_ciphertext(self) -> None:
        """`BYTEA` is how raw bytes would arrive if they ever did. There is
        exactly one, it holds Fernet ciphertext, and it is nullable because an
        account legitimately exists without a usable credential."""
        binary = [
            (table_name, column_name)
            for table_name, column_name, column in columns()
            if isinstance(column.type, LargeBinary)
        ]
        assert binary == [("connector_accounts", "encrypted_credentials")]

    def test_no_column_holds_a_plaintext_credential(self) -> None:
        """Third-party secrets exist in PostgreSQL only as ciphertext."""
        for table_name, column_name, _ in columns():
            if SECRET_PATTERN.search(column_name.lower()):
                assert (table_name, column_name) in SECRET_EXEMPT, (
                    f"{table_name}.{column_name} looks like a credential column"
                )

    def test_the_credential_column_is_binary_not_text(self) -> None:
        """A base64 `TEXT` column invites a `SELECT` during a debugging session
        and silently tolerates a plaintext write. `BYTEA` does neither."""
        column = table_named("connector_accounts").columns["encrypted_credentials"]

        assert isinstance(column.type, LargeBinary)
        assert column.nullable

    def test_signals_holds_no_entity_graph(self) -> None:
        """Neo4j owns the edges. `signals.entities` is the mention list the
        graph writer consumes, not the graph itself -- if an agent could learn
        something from one store that is not derivable from PostgreSQL plus R2,
        the rebuild guarantee is already broken."""
        signal_columns = set(table_named("signals").columns.keys())

        assert not {"edges", "relationships", "graph"} & signal_columns
